[CmdletBinding()]
param(
    [string]$OutputFile = '',
    [string]$Version = '1.0.0',
    [switch]$NoInstallPs2exe
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

if (-not $OutputFile) {
    $OutputFile = Join-Path (Get-Location).Path 'Win11Debloat.exe'
}

$RootDir = if ($PSScriptRoot) { $PSScriptRoot } elseif ($ScriptRoot) { $ScriptRoot } else { (Get-Location).Path }

Write-Host '=== Win11Debloat EXE Build Script ===' -ForegroundColor Cyan

# --- Step 1: Ensure ps2exe is available ---
if (-not (Get-Module -ListAvailable -Name ps2exe)) {
    if ($NoInstallPs2exe) {
        Write-Error 'ps2exe module not found. Install with: Install-Module ps2exe'
    }
    Write-Host 'Installing ps2exe module...' -ForegroundColor Yellow
    Install-Module ps2exe -Force -Scope CurrentUser
}
Import-Module ps2exe
Write-Host '[OK] ps2exe ready' -ForegroundColor Green

# --- Step 2: Create ZIP of all runtime files ---
$tempDir = Join-Path $env:TEMP "Win11Debloat_Build_$(Get-Random)"
$zipPath = Join-Path $tempDir 'payload.zip'
New-Item -ItemType Directory -Path $tempDir -Force | Out-Null

$includeItems = @(
    'Win11Debloat.ps1',
    'Run.bat',
    'Config',
    'Schemas',
    'Scripts',
    'Regfiles',
    'Assets',
    'LICENSE'
)

Write-Host 'Packaging runtime files...' -ForegroundColor Yellow
$payloadDir = Join-Path $tempDir 'payload'
New-Item -ItemType Directory -Path $payloadDir -Force | Out-Null

foreach ($item in $includeItems) {
    $src = Join-Path $RootDir $item
    if (Test-Path $src) {
        $dst = Join-Path $payloadDir $item
        if (Test-Path $src -PathType Container) {
            Copy-Item -Path $src -Destination $dst -Recurse -Force
        } else {
            Copy-Item -Path $src -Destination $dst -Force
        }
    }
}

Add-Type -AssemblyName System.IO.Compression.FileSystem
[System.IO.Compression.ZipFile]::CreateFromDirectory($payloadDir, $zipPath, [System.IO.Compression.CompressionLevel]::Optimal, $false)

$zipBytes = [System.IO.File]::ReadAllBytes($zipPath)
$zipBase64 = [Convert]::ToBase64String($zipBytes)
$zipSize = [math]::Round($zipBytes.Length / 1KB, 1)
Write-Host "[OK] Payload ZIP: ${zipSize} KB -> base64: $([math]::Round($zipBase64.Length / 1KB, 1)) KB" -ForegroundColor Green

# --- Step 3: Generate launcher script ---
$launcherPath = Join-Path $tempDir 'launcher.ps1'

$launcherScript = @"
# Win11Debloat Launcher - Single-file EXE wrapper
# Auto-generated by Build-Exe.ps1
# Version: $Version

`$ErrorActionPreference = 'Stop'

# Embedded payload (base64-encoded ZIP)
`$PayloadBase64 = @'
$zipBase64
'@

function Extract-Payload {
    param([string]`$TargetDir)

    if (Test-Path `$TargetDir) {
        Remove-Item `$TargetDir -Recurse -Force
    }
    New-Item -ItemType Directory -Path `$TargetDir -Force | Out-Null

    `$zipBytes = [Convert]::FromBase64String(`$PayloadBase64)
    `$zipPath = Join-Path `$env:TEMP "Win11Debloat_payload_`$(Get-Random).zip"
    [System.IO.File]::WriteAllBytes(`$zipPath, `$zipBytes)

    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::ExtractToDirectory(`$zipPath, `$TargetDir)
    Remove-Item `$zipPath -Force
}

# Main
`$extractDir = Join-Path `$env:TEMP 'Win11Debloat'
Write-Host 'Extracting Win11Debloat files...' -ForegroundColor Cyan
Extract-Payload -TargetDir `$extractDir

# Pass through all arguments to the main script
`$scriptPath = Join-Path `$extractDir 'Win11Debloat.ps1'
if (-not (Test-Path `$scriptPath)) {
    Write-Error 'Win11Debloat.ps1 not found in extracted payload!'
    exit 1
}

try {
    & `$scriptPath @args
} finally {
    # Clean up extracted files
    Remove-Item `$extractDir -Recurse -Force -ErrorAction SilentlyContinue
}
"@

[System.IO.File]::WriteAllText($launcherPath, $launcherScript, [System.Text.Encoding]::UTF8)
Write-Host '[OK] Launcher script generated' -ForegroundColor Green

# --- Step 4: Compile with ps2exe ---
Write-Host 'Compiling EXE with ps2exe...' -ForegroundColor Yellow

$ps2exeArgs = @{
    inputFile  = $launcherPath
    outputFile = $OutputFile
    title      = 'Win11Debloat'
    description = 'Windows 11 Debloat Tool - Chinese Localization Fork'
    product    = 'Win11Debloat-zh_Hans-zh_Hant'
    version    = $Version
    requireAdmin = $true
    supportOS  = $true
    longPaths  = $true
    noConsole  = $false
}

Invoke-PS2EXE @ps2exeArgs

if (Test-Path $OutputFile) {
    $exeSize = [math]::Round((Get-Item $OutputFile).Length / 1MB, 2)
    Write-Host "[OK] EXE created: $OutputFile (${exeSize} MB)" -ForegroundColor Green
} else {
    Write-Error 'EXE was not created!'
}

# --- Cleanup ---
Remove-Item $tempDir -Recurse -Force -ErrorAction SilentlyContinue
Write-Host '=== Build complete ===' -ForegroundColor Cyan
